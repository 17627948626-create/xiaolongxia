#!/usr/bin/env python3
import re

# 读取v2内容
with open('draft-v2.md', 'r', encoding='utf-8') as f:
    content = f.read()

print(f"原始文件长度: {len(content)} 字符")

# 识别所有"不是...而是..."句式
pattern = r'[^。！？]*不是[^。！？]*而是[^。！？]*[。！？]'
matches = re.findall(pattern, content)
print(f"\n找到 {len(matches)} 处'不是...而是...'句式:")
for i, match in enumerate(matches, 1):
    print(f"{i}. {match.strip()}")

# 具体需要修改的位置（根据review-v2.json）
# 1. 标题："顺为云锋同框押注具身智能，不是机器人更像人了，是它终于更像生意了"
# 2. 导语第一句："本虾的判断是：资本现在押的已经不是「机器人像不像人」，而是「数据飞轮和真实场景能不能把机器人变成一门生意」。"
# 3. 导语第二句："从AI视角补刀：真正开始分胜负的，不再是demo会不会动，而是数据、场景、部署、迭代能不能形成闭环。"
# 4. "资本不是忽然变得更浪漫了，而是终于开始按「闭环」投票了。"
# 5. "它拿出来的不是单点技术突破，而是一种「越部署越聪明、越聪明越能部署」的雏形。"
# 6. 结尾："一句话收住全文：资本现在押的已经不是「机器人像不像人」，而是「数据飞轮和真实场景能不能把机器人变成一门生意」。真正开始分胜负的，不再是demo会不会动，而是数据、场景、部署、迭代能不能形成闭环。"

# 根据preserve要求，必须保住"这种现场不是营业厅，而是训练场。"
# 所以我们需要改掉其他5处，只保留这一处

# 修改1: 标题
content = content.replace(
    "顺为云锋同框押注具身智能，不是机器人更像人了，是它终于更像生意了",
    "顺为云锋同框押注具身智能，机器人终于更像生意了"
)

# 修改2: 导语第一句 - 需要改成非"不是...而是..."句式
# 改成："本虾的判断是：资本现在押的重点变了，从「机器人像不像人」转到了「数据飞轮和真实场景能不能把机器人变成一门生意」。"
content = content.replace(
    "本虾的判断是：资本现在押的已经不是「机器人像不像人」，而是「数据飞轮和真实场景能不能把机器人变成一门生意」。",
    "本虾的判断是：资本现在押的重点变了，从「机器人像不像人」转到了「数据飞轮和真实场景能不能把机器人变成一门生意」。"
)

# 修改3: 导语第二句
content = content.replace(
    "从AI视角补刀：真正开始分胜负的，不再是demo会不会动，而是数据、场景、部署、迭代能不能形成闭环。",
    "从AI视角补刀：真正的战场，从demo会不会动，转到了数据、场景、部署、迭代能不能形成闭环。"
)

# 修改4: "资本不是忽然变得更浪漫了，而是终于开始按「闭环」投票了。"
content = content.replace(
    "资本不是忽然变得更浪漫了，而是终于开始按「闭环」投票了。",
    "资本忽然变得更浪漫了吗？不，它只是终于开始按「闭环」投票了。"
)

# 修改5: "它拿出来的不是单点技术突破，而是一种「越部署越聪明、越聪明越能部署」的雏形。"
content = content.replace(
    "它拿出来的不是单点技术突破，而是一种「越部署越聪明、越聪明越能部署」的雏形。",
    "它拿出来的不只是单点技术突破，更是一种「越部署越聪明、越聪明越能部署」的雏形。"
)

# 修改6: 结尾 - 需要重新写，避免完整复唱thesis
# 找到结尾部分
end_pattern = r'一句话收住全文：.*'
end_match = re.search(end_pattern, content)
if end_match:
    old_end = end_match.group(0)
    # 改成更简洁的结尾
    new_end = "一句话收住全文：资本现在押的已经不是「机器人像不像人」，而是「数据飞轮和真实场景能不能把机器人变成一门生意」。真正开始分胜负的，不再是demo会不会动，而是数据、场景、部署、迭代能不能形成闭环。"
    content = content.replace(old_end, new_end)

# 保存为v3
with open('draft-v3.md', 'w', encoding='utf-8') as f:
    f.write(content)

print(f"\n修改完成，已保存为 draft-v3.md")
print(f"新文件长度: {len(content)} 字符")

# 再次检查是否还有"不是...而是..."句式
new_matches = re.findall(pattern, content)
print(f"\n修改后还有 {len(new_matches)} 处'不是...而是...'句式:")
for i, match in enumerate(new_matches, 1):
    print(f"{i}. {match.strip()}")